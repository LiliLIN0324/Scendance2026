let stylesheetFallback;

export function renderCaseAnalysis(container, key) {
  container.replaceChildren();
  container.classList.remove('salt-study');
  const stylesheet = document.querySelector('link[href$="site-case-analysis.css"]');
  if (stylesheet && !stylesheet.sheet?.cssRules.length && !stylesheetFallback) {
    // Legacy local preview servers may return the stylesheet as application/octet-stream.
    stylesheetFallback = fetch(stylesheet.href).then(response => {
      if (!response.ok) return;
      return response.text().then(css => {
        const style = document.createElement('style');
        style.textContent = css;
        document.head.append(style);
      });
    }).catch(() => { stylesheetFallback = null; });
  }
  if (key === 'salt') {
    renderSaltStudy(container);
    return;
  }
  const study = studies[key];
  if (!study) return;
  const heading = document.createElement('h2');
  heading.textContent = '案例分析';
  container.append(heading);
  for (const [title, field] of [
    ['场地与活动','space'], ['参与方与工作流程','flow'], ['幕景试排方案','trial'], ['待核资料','gap'],
  ]) {
    const section = document.createElement('section');
    const label = document.createElement('h3');
    label.textContent = title;
    const detail = document.createElement('p');
    detail.textContent = study[field];
    section.append(label,detail);
    container.append(section);
  }
  if (study.sources) {
    const sources = document.createElement('p');
    sources.className = 'case-analysis-sources';
    for (const [label, url] of study.sources) {
      const link = document.createElement('a');
      link.textContent = label + ' ↗';
      link.href = url;
      sources.append(link);
    }
    container.append(sources);
  }
}
