import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';

const css = readFileSync(resolve(dirname(fileURLToPath(import.meta.url)), '../../../app/globals.css'), 'utf8');
const start = css.indexOf('.oc-cluster.oc-br.oc-gmaps {');
const end = css.indexOf('.sc-workbench .sc-tool-pop', start);
const block = css.slice(start, end);

it('matches the measured Google map-control spacing, roundness, and shadow', () => {
  expect(start).toBeGreaterThan(0);
  expect(end).toBeGreaterThan(start);
  expect(block).toContain('--oc-gm-control: 29px');
  expect(block).toContain('--oc-gm-compass: 44px');
  expect(block).toContain('--oc-gm-gap: 4px');
  expect(block).toContain('--oc-gm-radius: calc(var(--oc-gm-control) * 0.28)');
  expect(block).toContain('--oc-gm-shadow: 0 1px 4px -1px rgba(0, 0, 0, .30), 0 2px 6px rgba(60, 64, 67, .16)');
  expect(block).toContain('--oc-gm-inset-x: 20px');
  expect(block).toContain('--oc-gm-inset-y: 20px');
  expect(block).toContain('right: var(--oc-gm-inset-x); bottom: var(--oc-gm-inset-y)');
  expect(block).toContain('--oc-gm-inset-x: 12px');
  expect(block).toContain('--oc-gm-inset-y: 14px');
  expect(block).toContain('--oc-gm-shadow-hover: 0 1px 4px -1px rgba(0, 0, 0, .30), 0 4px 10px rgba(60, 64, 67, .20)');
  expect(block).toContain('--oc-gm-compass-shadow: 0 1px 3px rgba(20, 20, 22, .28), 0 2px 8px rgba(20, 20, 22, .18)');
  expect(block).toContain('--oc-gm-compass-shadow-hover: 0 1px 4px rgba(20, 20, 22, .34), 0 3px 10px rgba(20, 20, 22, .22)');
  expect(block).toContain('--oc-gm-shadow-active: 0 0 0 2px #1a73e8, 0 1px 4px -1px rgba(0, 0, 0, .30), 0 2px 6px rgba(26, 115, 232, .22)');
  expect(block).toContain('--oc-gm-shadow-ghost: 0 1px 4px rgba(20, 20, 22, .10)');
  expect(block).toContain('--oc-gm-pop-shadow: 0 1px 2px rgba(60, 64, 67, .30), 0 2px 6px rgba(60, 64, 67, .15)');
  expect(block).toContain('border-radius: var(--oc-gm-radius)');
  expect(block).toContain('box-shadow: var(--oc-gm-shadow);');
  expect(block).toContain('box-shadow: var(--oc-gm-shadow-hover)');
  expect(block).toContain('box-shadow: var(--oc-gm-compass-shadow);');
  expect(block).toContain('box-shadow: var(--oc-gm-compass-shadow-hover)');
  expect(block).toContain('box-shadow: var(--oc-gm-shadow-active)');
  expect(block).toContain('box-shadow: var(--oc-gm-shadow-ghost)');
  expect(block).toContain('box-shadow: var(--oc-gm-pop-shadow)');
  expect(block).toContain('top: calc(var(--oc-gm-gap) * 2)');
  expect(block).toContain('left: var(--oc-gm-gap)');
  expect(block).toContain('right: calc(100% + var(--sp-2))');
  expect(block).toContain('padding: var(--sp-2) var(--sp-3)');
  expect(block).toContain('align-items: center');
  expect(block.split('0 1px 3px rgba(20, 20, 22, .28), 0 2px 8px rgba(20, 20, 22, .18)')).toHaveLength(2);
  expect(block).toContain('flex-direction: column; border-radius: var(--oc-gm-radius); overflow: visible;');
  expect(block).toContain('left: 5px; right: 5px; top: 50%;');
  expect(block).toContain('background-size: 13px 13px');
  expect(block).toContain("stroke='%235f6368' stroke-width='3' stroke-linecap='round'");
  expect(block).not.toContain('border-bottom: 1px solid rgba(60, 64, 67, .22)');
});
